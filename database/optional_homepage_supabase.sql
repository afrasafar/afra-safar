CREATE TABLE IF NOT EXISTS public.homepage_reviews (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 display_name text NOT NULL,
 city text,
 comment text NOT NULL,
 rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
 is_approved boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.homepage_reviews ENABLE ROW LEVEL SECURITY;
-- Public reads are restricted to approved comments; creating/updating reviews is handled by your administrator.
DROP POLICY IF EXISTS "Read approved homepage reviews" ON public.homepage_reviews;
CREATE POLICY "Read approved homepage reviews" ON public.homepage_reviews FOR SELECT TO anon, authenticated USING (is_approved = true);
GRANT SELECT ON public.homepage_reviews TO anon, authenticated;
